// Package haproxy renders the shared HAProxy configuration from services.yaml
// and talks to the running HAProxy through its runtime API (admin socket).
package haproxy

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"net/netip"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"github.com/mgh3326/shiftgate/internal/config"
	"github.com/mgh3326/shiftgate/internal/state"
)

// ErrWildcardBind is returned when a bind is a wildcard and wildcards are not
// explicitly allowed.
var ErrWildcardBind = errors.New("wildcard bind refused")

// Render produces the whole configuration. enabled maps a blue-green service
// to its committed active colour; a service missing from it has both colours
// disabled (never deployed). allowWildcard is the explicit CLI permission;
// haproxy.allow_wildcard_bind in services.yaml grants the same.
func Render(f *config.File, enabled map[string]config.Color, allowWildcard bool) ([]byte, error) {
	allowWildcard = allowWildcard || f.HAProxy.AllowWildcardBind
	allowed := map[netip.Addr]bool{}
	for _, a := range f.HAProxy.AllowedBinds {
		if ip, err := netip.ParseAddr(a); err == nil {
			allowed[ip] = true
		}
	}
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	h := f.HAProxy
	w("# Generated by shiftgate from services.yaml. Do not edit: `shiftgate render` overwrites it.")
	w("global")
	w("    log %s", h.Log)
	w("    master-worker")
	w("    stats socket %s mode 600 level admin", h.SocketInConfig)
	w("")
	w("defaults")
	w("    log global")
	w("    mode http")
	w("    option dontlognull")
	w("    timeout connect %s", hd(h.Timeouts.Connect))
	w("    timeout client %s", hd(h.Timeouts.Client))
	w("    timeout server %s", hd(h.Timeouts.Server))
	if h.Timeouts.Tunnel != 0 {
		w("    timeout tunnel %s", hd(h.Timeouts.Tunnel))
	}
	w("    timeout http-request %s", hd(h.Timeouts.HTTPRequest))
	for _, s := range f.Services {
		w("")
		w("frontend %s", s.Frontend)
		w("    mode %s", s.Mode)
		for _, bind := range s.Binds {
			ip, err := config.BindAddr(bind)
			if err != nil {
				return nil, fmt.Errorf("service %s: bind %s: %w", s.Name, bind, err)
			}
			switch {
			case ip.IsUnspecified() && !allowWildcard:
				return nil, fmt.Errorf("service %s: bind %s: %w (pass --allow-wildcard-bind or set haproxy.allow_wildcard_bind)", s.Name, bind, ErrWildcardBind)
			case !ip.IsUnspecified() && !allowed[ip]:
				return nil, fmt.Errorf("service %s: bind %s is not in haproxy.allowed_binds", s.Name, bind)
			}
			w("    bind %s", bind)
		}
		w("    default_backend %s", s.Backend)
		w("")
		w("backend %s", s.Backend)
		w("    mode %s", s.Mode)
		if s.Health.HTTP != "" {
			w("    option httpchk GET %s", s.Health.HTTP)
			w("    http-check expect status %d", s.Health.ExpectStatus)
		}
		w("    default-server inter %s fall %d rise %d", hd(s.Check.Inter), s.Check.Fall, s.Check.Rise)
		if s.Static() {
			w("    server %s %s check", strings.ReplaceAll(s.Name, "-", "_"), s.Upstream)
			continue
		}
		active, deployed := enabled[s.Name]
		for _, c := range []config.Color{config.Blue, config.Green} {
			line := fmt.Sprintf("    server %s 127.0.0.1:%d check", c, s.Port(c))
			if !deployed || c != active {
				line += " disabled"
			}
			w("%s", line)
		}
	}
	return b.Bytes(), nil
}

// hd formats a duration the way HAProxy reads it (ms/s/m/h, integer).
func hd(d config.Duration) string {
	v := d.D()
	switch {
	case v%time.Hour == 0:
		return fmt.Sprintf("%dh", v/time.Hour)
	case v%time.Minute == 0:
		return fmt.Sprintf("%dm", v/time.Minute)
	case v%time.Second == 0:
		return fmt.Sprintf("%ds", v/time.Second)
	default:
		// Round up so a non-zero sub-millisecond value never renders as 0ms.
		return fmt.Sprintf("%dms", (v+time.Millisecond-1)/time.Millisecond)
	}
}

// WildcardsApproved reports whether every wildcard bind in f already
// appears as a bind line of the installed config, i.e. an earlier explicit
// render approved it. With no wildcard binds it reports false (nothing to
// approve); a missing file approves nothing.
func WildcardsApproved(f *config.File) (bool, error) {
	var wild []string
	for _, s := range f.Services {
		for _, b := range s.Binds {
			if ip, err := config.BindAddr(b); err == nil && ip.IsUnspecified() {
				wild = append(wild, b)
			}
		}
	}
	if len(wild) == 0 {
		return false, nil
	}
	cur, err := os.ReadFile(f.HAProxy.Config)
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	lines := map[string]bool{}
	for _, l := range strings.Split(string(cur), "\n") {
		lines[strings.TrimSpace(l)] = true
	}
	for _, b := range wild {
		if !lines["bind "+b] {
			return false, nil
		}
	}
	return true, nil
}

// Enabled reads every blue-green service's committed active colour. It
// refuses when any service has an unresolved in-flight operation, because
// the committed state would then disagree with what HAProxy is routing.
func Enabled(f *config.File, st state.Store) (map[string]config.Color, error) {
	out := map[string]config.Color{}
	for _, s := range f.Services {
		if s.Static() {
			continue
		}
		cur, err := st.Load(s.Name)
		if errors.Is(err, state.ErrNoState) {
			continue
		}
		if err != nil {
			return nil, err
		}
		if cur.Pending != nil {
			return nil, fmt.Errorf("service %s has an unresolved %s (op %s, phase %s); run `shiftgate recover %s` first",
				s.Name, cur.Pending.Op, cur.Pending.OpID, cur.Pending.Phase, s.Name)
		}
		if cur.Active != nil {
			out[s.Name] = cur.Active.Color
		}
	}
	return out, nil
}

// Validate runs the configured check command against a candidate file.
func Validate(ctx context.Context, f *config.File, path string) error {
	argv := make([]string, len(f.HAProxy.Check))
	for i, a := range f.HAProxy.Check {
		argv[i] = strings.ReplaceAll(a, "{config}", path)
	}
	ctx, cancel := context.WithTimeout(ctx, 60*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, argv[0], argv[1:]...).CombinedOutput()
	if err != nil {
		return fmt.Errorf("haproxy config check failed: %w\n%s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

// Install validates data as a candidate next to the live file and then
// installs it. An existing file keeps its inode (overwritten in place after
// a .previous backup) so a file bind-mounted into a container sees the new
// content; a new file is renamed into place.
func Install(ctx context.Context, f *config.File, data []byte) error {
	path := f.HAProxy.Config
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	cand := path + ".candidate"
	if err := os.WriteFile(cand, data, 0o644); err != nil {
		return err
	}
	defer os.Remove(cand)
	if err := Validate(ctx, f, cand); err != nil {
		return err
	}
	cur, err := os.ReadFile(path)
	switch {
	case errors.Is(err, os.ErrNotExist):
		return state.WriteFileAtomic(path, data, 0o644)
	case err != nil:
		return err
	case bytes.Equal(cur, data):
		return nil
	}
	if err := state.WriteFileAtomic(path+".previous", cur, 0o644); err != nil {
		return err
	}
	if err := overwrite(path, data); err != nil {
		if rerr := overwrite(path, cur); rerr != nil {
			return fmt.Errorf("%w; restoring the previous config also failed (copy %s.previous back): %v", err, path, rerr)
		}
		return err
	}
	return nil
}

// overwrite replaces path's content in place (same inode) and syncs it.
func overwrite(path string, data []byte) error {
	out, err := os.OpenFile(path, os.O_WRONLY|os.O_TRUNC, 0)
	if err != nil {
		return err
	}
	if _, err := out.Write(data); err != nil {
		out.Close()
		return err
	}
	if err := out.Sync(); err != nil {
		out.Close()
		return err
	}
	return out.Close()
}

// Reload runs the configured reload command.
func Reload(ctx context.Context, f *config.File) error {
	argv := f.HAProxy.Reload
	ctx, cancel := context.WithTimeout(ctx, 60*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, argv[0], argv[1:]...).CombinedOutput()
	if err != nil {
		return fmt.Errorf("haproxy reload failed: %w\n%s", err, strings.TrimSpace(string(out)))
	}
	return nil
}
